args <- commandArgs(trailingOnly=TRUE)
root <- normalizePath(args[1L])
work <- normalizePath(args[2L])
project <- normalizePath(file.path(root, "../.."))
source(file.path(root, "src/background.R"))
source(file.path(project, "experiments/readable-experiments/R/gaussian_tests.R"))
source(file.path(project, "experiments/readable-experiments/R/linear_tests.R"))
con <- file(file.path(work, "reference-input.bin"), "rb")
y <- readBin(con, "double", 80L, size=8L, endian="little")
xs <- matrix(readBin(con, "double", 80L*112L, size=8L, endian="little"), 80L)
candidate_values <- readBin(con, "double", 12L*80L*8L, size=8L, endian="little")
close(con)
seed <- 123456L
new <- background_lasso(xs, y, seed)
RNGkind("Mersenne-Twister", "Inversion", "Rejection")
set.seed(seed)
old <- lasso_background_fit(xs, y)
stopifnot(identical(new$fitted, old))
all_t <- matrix(NA_real_, 12L, 8L)
sst <- numeric(12L)
for (k in seq_len(12L)) {
  x <- matrix(candidate_values[(1L+(k-1L)*640L):(k*640L)], 80L)
  model <- glm(new$residual ~ x, family="gaussian")
  stopifnot(model$rank == 9L, model$df.residual == 71L)
  all_t[k,] <- summary(model)$coefficients[-1L,3L]
  sst[k] <- linear_statistic(x, new$residual, 1:8, "LM-SST")
}
stopifnot(max(abs(rowSums(all_t^2)-sst)) == 0)
write.table(all_t, file.path(work,"R-coefficient-t.csv"), sep=",", row.names=FALSE, col.names=FALSE)
con <- file(file.path(work,"R-residual.bin"),"wb")
writeBin(new$residual,con,size=8L,endian="little"); close(con)
writeLines(capture.output(sessionInfo()),file.path(work,"R-sessionInfo.txt"))
cat("Original Lasso fit is bitwise identical; 12 joint GLM t vectors extracted.\n")
